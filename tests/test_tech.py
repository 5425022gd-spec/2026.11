def test_data():
    trees = tech.trees()
    ok([t["id"] for t in trees] == ["theory", "applied"], "两棵树＝理论科学 科学技术，实际 %s" % trees)
    names = [t.get("name") for t in tech.all_techs()]
    ok(len(names) == len(set(names)), "科技名不得重复")
    for t in tech.all_techs():
        ok(t.get("tree") in [x["id"] for x in trees], "%s 的树不合法" % t["id"])
        ok(0 < float(t.get("x", 0)) < 9000 and 0 < float(t.get("y", 0)) < 4000,
           "%s 的坐标要落在 keji.png 的画布内（零点＝图片左上角），实际 (%s, %s)"
           % (t["id"], t.get("x"), t.get("y")))
        for p in t["prereqs"]:
            ok(p in [x["id"] for x in tech.all_techs()], "%s 的前置 %s 不存在" % (t["id"], p))
        ok(tech.cost_of(t["id"]) > 0, "%s 的解锁消耗要写在数据里且大于 0" % t["id"])
    miss = [n for n in ABSENT if n in names]
    ok(not miss, "图上没有的名目不该写进来：%s" % miss)
    for t in tech.all_techs():
        for key in ("name",):
            for bad in ("（", "）", "·", "《", "》"):
                ok(bad not in t[key], "%s 的名字里不该有 %s" % (t[key], bad))
    print("数据完整性 ✓ %d 条科技，坐标都在画布内，图上没有的名目未写入" % len(names))


def test_prereqs():
    byid = {t["id"]: t for t in tech.all_techs()}
    nm = by_name()
    ok(len(EXPECT_PREREQS) <= len(nm), "关系代码里的名目都得在数据里")
    for name, pres in EXPECT_PREREQS.items():
        t = nm.get(name)
        ok(t is not None, "缺科技 %s" % name)
        got = sorted(tech.tech_name(p) for p in tech.prereqs_of(t["id"]))
        ok(got == sorted(pres), "%s 的前置应为 %s，实际 %s" % (name, sorted(pres), got))

    # 后置由前置反查
    def post(name):
        return sorted(tech.tech_name(x) for x in tech.dependents_of(nm[name]["id"]))
    ok(post("初等数学") == ["中等数学"], "初等数学后置＝中等数学")
    ok(post("科学方法") == ["中等化学", "中等地理", "中等物理"],
       "科学方法后置，实际 %s" % post("科学方法"))
    ok(post("中等化学") == ["中等生物", "无机化学", "普通地质学"],
       "中等化学后置，实际 %s" % post("中等化学"))
    # "前置的前置"不再单列
    ok(nm["环境工程"]["prereqs"] and "wuji_huaxue" not in nm["环境工程"]["prereqs"],
       "环境工程不再单列无机化学（物理化学已含）")
    ok("jingji_dilixue" not in nm["城乡规划"]["prereqs"],
       "城乡规划不再单列经济地理学（城市地理学已含）")
    ok("renwen_dilixue" not in nm["城市地理学"]["prereqs"],
       "城市地理学不再单列人文地理学（经济地理学已含）")

    # 无环：反复剥掉无前置的节点，应能剥完
    remain = {t["id"]: set(t["prereqs"]) for t in tech.all_techs()}
    done = set()
    while True:
        ready = [k for k, v in remain.items() if not (v - done)]
        if not ready:
            break
        for k in ready:
            done.add(k)
            remain.pop(k)
    ok(not remain, "前置关系有环：%s" % [byid[k]["name"] for k in remain])
    # 每棵树各有自己的根：理论科学＝初等数学 科学方法；科学技术＝炼钢基础 鼓风 机械结构基础 地理测绘基础
    roots_by_tree = {}
    for t in tech.all_techs():
        if not t["prereqs"]:
            roots_by_tree.setdefault(t["tree"], []).append(t["name"])
    for tree in roots_by_tree:
        roots_by_tree[tree] = sorted(roots_by_tree[tree])
    ok(roots_by_tree.get("theory") == ["初等数学", "科学方法"],
       "理论科学的根，实际 %s" % roots_by_tree.get("theory"))
    ok(roots_by_tree.get("applied") == ["地理测绘基础", "机械结构基础", "炼钢基础", "鼓风"],
       "科学技术的根，实际 %s" % roots_by_tree.get("applied"))
    print("前后置关系 ✓ 无环；理论科学根＝初等数学 科学方法，科学技术根＝%s；%d 条科技"
          % ("、".join(roots_by_tree.get("applied") or []), len(byid)))


def test_unlock_gate():
    st = load_state()
    nm = by_name()
    ok(abs(tech.points(st) - 10.0) < 1e-9, "开局科技点应为 10，实际 %s" % tech.points(st))
    ok(tech.unlocked_ids(st) == [], "开局科技全部未解锁")

    ok(not tech.prereqs_met(st, nm["中等化学"]["id"]), "前置未完成时中等化学不该满足前置")
    st.tech_unlocked.append(nm["初等数学"]["id"])
    ok(not tech.prereqs_met(st, nm["中等化学"]["id"]), "只完成初等数学仍缺科学方法与中等数学")
    st.tech_unlocked.append(nm["科学方法"]["id"])
    ok(not tech.prereqs_met(st, nm["中等化学"]["id"]), "有了科学方法还缺中等数学")
    st.tech_unlocked.append(nm["中等数学"]["id"])
    ok(tech.prereqs_met(st, nm["中等化学"]["id"]), "科学方法与中等数学都完成后中等化学满足前置")
    ok(not tech.prereqs_met(st, nm["无机化学"]["id"]), "无机化学还要等中等化学")
    ok(tech.prereqs_met(st, nm["中等地理"]["id"]), "中等地理只需科学方法")
    print("解锁门槛 ✓ 前置未完成不放行，前置完成即放行")


def test_unlock_cost_and_rules():
    st = load_state()
    nm = by_name()
    okk, msg = tech.unlock(st, nm["无机化学"]["id"])
    ok(not okk and "前置未完成" in msg, "前置未完成不给解锁，实际 %s" % msg)
    ok(abs(tech.points(st) - 10.0) < 1e-9, "失败不得扣点")

    okk, msg = tech.unlock(st, nm["初等数学"]["id"])
    ok(okk, "初等数学可解锁，实际 %s" % msg)
    ok(abs(tech.points(st) - 9.0) < 1e-9, "解锁后应扣 1 点，实际 %s" % tech.points(st))
    okk, msg = tech.unlock(st, nm["初等数学"]["id"])
    ok(not okk and "已解锁" in msg, "重复解锁要拒，实际 %s" % msg)
    ok(abs(tech.points(st) - 9.0) < 1e-9, "重复解锁不得再扣点")

    tid = nm["科学方法"]["id"]
    ok(tech.unlock_text(st, tid) == "消耗1科技点解锁", "可解锁文案，实际 %s" % tech.unlock_text(st, tid))
    ok(tech.unlock_text(st, nm["中等物理"]["id"]) == "前置未完成", "前置未完成文案")

    st.tech_points = 0.5
    ok(tech.unlock_state(st, tid) == "科技点不足", "点数不足的判定")
    ok(tech.unlock_text(st, tid) == "科技点不足", "点数不足文案")
    okk, msg = tech.unlock(st, tid)
    ok(not okk and "科技点不足" in msg, "点数不足不给解锁")

    st.tech_points = 5.0
    st.tech_unlocked = [nm["初等数学"]["id"]]
    ok(tech.prereqs_met(st, nm["中等数学"]["id"]), "中等数学前置＝初等数学，此时应已满足")
    ok(tech.unlock_state(st, nm["高等数学"]["id"]) == "前置未完成", "高等数学还差中等数学")
    print("解锁消耗与规则 ✓ 前置未完成不放行 扣点 重复解锁拒绝 点数不足拒绝")


