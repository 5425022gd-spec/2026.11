def build_dept(name, state):
    """组装部门详情：管理层一律读官职表（京官 · 本部门），缺员就显示缺员。"""
    from .depts_neiting import DEPTS as NEITING_DEPTS
    from .depts_palaces import PALACES as PALACE_DEPTS
    from . import positions as _pos
    from .factions import get_character_faction
    # WAIDEPS 兜底：超控「增加部门」是在运行时往 depts_waizhusi.DEPTS 里加的，
    # 而 DEPTS 是导入时合并出来的副本，不查 WAIDEPS 的话新建部门打不开
    cfg = (DEPTS.get(name) or NEITING_DEPTS.get(name) or PALACE_DEPTS.get(name)
           or WAIDEPS.get(name))
    if not cfg:
        return None
    staff = []
    for row in _pos.rows(kind="京官", category=name):
        person = row.get("person") or ""
        fac = (get_character_faction(person, title=row["title"],
                                     location=row.get("location", "")) if person else "—")
        staff.append({"name": person, "title": row["title"], "faction": fac,
                      "start": row.get("start_date") or "?",
                      "location": row.get("location") or "?",
                      "vacant": not person})
    # 本部门年费 部门自己的属性，数据在 world/department_expenses.json；户部只做统计
    # 宫殿、城门这类设施不是部门，没有年费，额度为 None，界面据此不显示这一栏
    from .depts_hubu import department_expense_of
    expense = department_expense_of(name) or {}
    return {
        "name": name,
        "intro": cfg["intro"],
        "alias": cfg.get("alias", []),
        "history": cfg.get("history", []),
        "suboffices": cfg.get("suboffices", []),
        "staff": staff,
        "headcount": cfg.get("headcount", ""),
        "annual_expense": expense.get("annual"),
        "monthly_expense": expense.get("monthly"),
        "expense_group": expense.get("group"),
        "routine": cfg.get("routine", []),
        "figures": cfg.get("figures", []),
        "anecdotes": cfg.get("anecdotes", []),
        "quotes": cfg.get("quotes", []),
        "sources": cfg.get("sources", []),
        "note": cfg.get("note", ""),
        "data": _engine_data(name, state) + _season_notes(name, state),
    }


