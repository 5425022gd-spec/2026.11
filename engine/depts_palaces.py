def room_names() -> list:
    """紫禁城地图上的殿宇名册 唯一来源：png/room.txt 的标注。

    行格式「殿名，x，y」；文件读不到或格式不对就报错，不静默给空表。
    """
    names = []
    with open(ROOM_MAP_TXT, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split("，")
            if len(parts) < 3:
                raise ValueError ("png/room.txt 行格式应为「殿名，x，y」：%r" % line)
            names.append(parts[0].strip())
    return names
