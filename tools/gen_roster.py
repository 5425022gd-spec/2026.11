def add_months(ym, n):
    y, m = (int(x) for x in ym.split("-"))
    m += n
    while m > 12:
        m -= 12
        y += 1
    return "%04d-%02d" % (y, m)


def gen_tenure():
    """任起 1621-01~1627-05，任期 36~96 月（3~8 年）；
    任止不早于 1629-01（开局近两年内不换人）；被推后的任止摊开到 1629-1632。"""
    start = "%04d-%02d" % (random.randint(1621, 1626), random.randint(1, 12))
    if start > "1627-05":
        start = "1627-%02d" % random.randint(1, 5)
    end = add_months(start, random.randint(36, 96))
    if end < "1629-01":
        end = add_months("1629-01", random.randint(0, 47))
    return start, end


def gen_name(used):
    while True:
        n = random.choice(SURNAMES) + random.choice(GIVEN_NAMES)
        if n not in used:
            used.add(n)
            return n


